#!/usr/bin/env python3
"""Generate ito_symbols.inc (sorted code point -> token id) from ito/text.py's SYMBOL_ID (StyleTTS 2 symbol table)."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(here, "../../..")))
from ito.text import SYMBOL_ID, SYMBOLS
items = sorted((ord(c), i) for c, i in SYMBOL_ID.items())
assert all(len(c) == 1 for c in SYMBOL_ID)
with open(os.path.join(here, "../ito_symbols.inc"), "w") as f:
    f.write("/* generated by tools/gen_symbols.py from ito/text.py (StyleTTS 2 symbol table, MIT, (c) 2023 Aaron (Yinghao) Li): do not edit */\n")
    f.write("#define ITOFE_N_SYMBOLS %d\n" % len(items))
    f.write("static const struct { unsigned short cp; unsigned char id; } itofe_symtab[ITOFE_N_SYMBOLS] = {\n")
    for k in range(0, len(items), 8):
        f.write("    " + " ".join("{0x%04X,%d}," % x for x in items[k:k + 8]) + "\n")
    f.write("};\n")
print(len(items), "symbols;", len(SYMBOLS), "table entries")
